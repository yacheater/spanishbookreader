let current = null;
function sentenceAround(para, idx, idxEnd = idx) {
  const parts = para.map((t) => (typeof t === "string" ? t : t[0]));
  let start = 0, end = parts.length;
  for (let i = idx - 1; i >= 0; i--) {
    if (typeof para[i] === "string" && /[.!?:;]/.test(para[i])) {
      const m = para[i].match(/^[\s\S]*[.!?:;]["”’»)]*\s*/);
      parts[i] = para[i].slice(m[0].length); start = i; break;
    }
  }
  for (let i = idxEnd + 1; i < para.length; i++) {
    if (typeof para[i] === "string" && /[.!?]/.test(para[i])) {
      const m = para[i].match(/^[^.!?]*[.!?]["”’»]*/);
      parts[i] = m[0]; end = i + 1; break;
    }
  }
  return { before: parts.slice(start, idx).join("").replace(/^[\s“"‘]+/, ""), word: parts.slice(idx, idxEnd + 1).join(""),
    after: parts.slice(idxEnd + 1, end).join("") };
}
