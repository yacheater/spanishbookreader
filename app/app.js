// ---------- reader ----------
let current = null;
function sentenceAround(para, idx, idxEnd = idx) {
  const parts = para.map((t) => (typeof t === "string" ? t : t[0]));
  let start = 0, end = parts.length;
  for (let i = idx - 1; i >= 0; i--) {
    if (typeof para[i] === "string" && /[.!?:;]/.test(para[i])) {
      const m = para[i].match(/^[\s\S]*[.!?:;]["”’»)]*\s*/);
      parts[i] = para[i].slice(m[0].length); start = i; break;
    }
  }
  for (let i = idxEnd + 1; i < para.length; i++) {
    if (typeof para[i] === "string" && /[.!?]/.test(para[i])) {
      const m = para[i].match(/^[^.!?]*[.!?]["”’»]*/);
      parts[i] = m[0]; end = i + 1; break;
    }
  }
  return { before: parts.slice(start, idx).join("").replace(/^[\s“"‘]+/, ""), word: parts.slice(idx, idxEnd + 1).join(""),
    after: parts.slice(idxEnd + 1, end).join("") };
}
async function renderReader(id) {
  view.innerHTML = `<div class="empty">Loading…</div>`;
  let t;
  try { t = await loadText(id); } catch (e) { t = null; }
  if (!t) { view.innerHTML = `<div class="empty">Text not found.</div>`; return; }
  current = t;
  // saved cards keep a copy of the lemma: refresh it from the current build (new fields like vos, fixed glosses)
  let refreshed = false;
  for (const c of Object.values(S.cards)) {
    const fresh = c.L.pos !== "phrase" && t.lemmas[c.key];
    if (fresh && JSON.stringify(fresh) !== JSON.stringify(c.L)) { c.L = fresh; refreshed = true; }
  }
  if (refreshed) Store.save();
  const ch = t.chapters[0];
  const heads = new Set(ch.headings || []);
  // token -> phrase occurrences; contiguous occurrences also underline the spaces between their words
  const occAt = {}, gapAt = {};
  (ch.phraseOcc || []).forEach((o, oi) => {
    o.t.forEach((ti) => { (occAt[o.p + ":" + ti] = occAt[o.p + ":" + ti] || []).push(oi); });
    const para = ch.paragraphs[o.p];
    const contiguous = o.t.every((ti, k) => k === 0 || para.slice(o.t[k - 1] + 1, ti).every((x) => typeof x === "string"));
    if (contiguous) for (let ti = o.t[0] + 1; ti < o.t[o.t.length - 1]; ti++) if (typeof para[ti] === "string") gapAt[o.p + ":" + ti] = oi;
  });
  t._occAt = occAt;
  let html = `<article class="col reader"><h1>${esc(t.title)}</h1>`;
  ch.paragraphs.forEach((para, pi) => {
    const inner = para.map((tok, ti) => {
      const g = gapAt[pi + ":" + ti];
      if (typeof tok === "string") return g === undefined ? esc(tok) : `<span class="ph ${phClass(t, g)}" data-o="${g}">${esc(tok)}</span>`;
      if (!tok[1]) return `<span class="w unk">${esc(tok[0])}</span>`;
      const key = t.forms[tok[1]].lemma, occ = occAt[pi + ":" + ti];
      return `<span class="w${S.cards[key] ? " learning" : ""}${occ ? " ph " + phClass(t, occ[0]) : ""}"${occ ? ` data-o="${occ.join(",")}"` : ""} data-p="${pi}" data-t="${ti}">${esc(tok[0])}</span>`;
    }).join("");
    html += heads.has(pi) ? `<h3>${inner}</h3>` : `<p>${inner}</p>`;
  });
  html += `<p class="src">Source: ${t.source.ref ? `<a href="${esc(t.source.ref)}" target="_blank" rel="noopener">${esc(t.source.ref)}</a>` : esc(t.source.kind)}${t.source.edited ? "<br>" + esc(t.source.edited) : ""}</p></article>`;
  view.innerHTML = html;
  const pos = S.positions[id];
  if (pos) requestAnimationFrame(() => window.scrollTo(0, pos * (document.body.scrollHeight - innerHeight)));
}
function phClass(t, oi) {
  const P = t.phrases[t.chapters[0].phraseOcc[oi].ph];
  return "ph-" + P.type + (S.cards[phraseKey(P)] ? " ph-saved" : "");
}
