// ---------- storage ----------
const KEY = "lector.v1";
const Store = {
  state: null,
  load() {
    let s = null;
    try { s = JSON.parse(localStorage.getItem(KEY)); } catch (e) { s = null; }
    this.state = Object.assign({
      settings: { fs: { mobile: 18, desktop: 20 }, lh: "normal", width: "narrow", theme: "auto" },
      cards: {}, known: {}, folders: {}, positions: {}, hidden: {}, selected: [], statusFilter: "all",
    }, s || {});
    if (!Array.isArray(this.state.selected)) this.state.selected = [];
    Sync.init(this.state);
    return this.state;
  },
  save(fromRemote) {
    const changed = Sync.stamp(this.state);
    try { localStorage.setItem(KEY, JSON.stringify(this.state)); } catch (e) { /* private mode */ }
    updateBadges();
    if (changed && !fromRemote) Cloud.schedule(this.state, (r) => this.save(r));
  },
};
const S = Store.load();

