/* Lector — reader + flashcards. Plain JS, no build step. Data: data/index.js + data/<id>.js
   (generated by tools/build_text.py). Progress lives in localStorage under "lector.v1"
   (Store below is the only place that touches it — Supabase sync plugs in there).

   Sync: app/sync.js — Sync.stamp() diffs every save, Cloud pushes/pulls through Supabase when
   app/config.js is filled in and you are signed in; otherwise everything stays in this browser.

   Learning model: Flashcards / Choose / In context are PRACTICE (stats only). Only the Write test
   (and Review, which is the Write test on due words) schedules words and marks them learned. */
