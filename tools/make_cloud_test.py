"""Regenerate tools/cloud_test.html from app/index.html: the real app wired to the in-memory fake Supabase
(tools/fake_supabase.js) with the local data files. Run after changing app/index.html."""
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
s = (ROOT / "app/index.html").read_text(encoding="utf-8")
s = s.replace("<head>", '<head>\n<base href="/app/">\n<!-- GENERATED by tools/make_cloud_test.py: app/index.html with a fake Supabase. -->', 1)
cdn = '<script src="https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2/dist/umd/supabase.js"></script>'
assert cdn in s
data = "".join(f'<script src="data/{p.stem}.js"></script>' for p in sorted((ROOT / "app/data").glob("*.js")) if p.stem != "index")
s = s.replace(cdn, '''<script src="/tools/fake_supabase.js"></script>
''' + data + '''
<script>
  if (!FAKE.db.texts.length) for (const t of Object.values(window.LECTOR_TEXTS))
    FAKE.db.texts.push({ id: t.id, owner: ["own", "public domain", "CC BY 4.0"].includes(t.license) ? "u2" : "u1",
      public: ["own", "public domain", "CC BY 4.0"].includes(t.license), title: t.title,
      meta: { source: t.source.ref, words: 1, lang: t.lang || "es", glosses: t.glosses || [], license: t.license,
      phrases: Object.values(t.phrases || {}).filter((p) => ["idiom", "collocation", "phrasal"].includes(p.type))
        .map((p) => ({ key: p.key, type: p.type, en: p.en, ru: p.ru, example: p.example })) }, data: t, updated_at: "" });
  FAKE.persist(); window.LECTOR_TEXTS = {};
</script>''')
import re
s = re.sub(r'<script src="config\.js\?v=\d+"></script>\n?', "", s)
s = re.sub(r'<script src="data/index\.js[^>]*></script>', "<script>window.LECTOR_INDEX=[];</script>", s)
(ROOT / "tools/cloud_test.html").write_text(s, encoding="utf-8")
print("tools/cloud_test.html regenerated")
